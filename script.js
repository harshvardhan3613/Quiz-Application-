// Variables

let category = "";
let subcategory = "";
let difficulty = "";

let questions = [];
let questionNumber = 0;
let score = 0;


/* -------------------------
   CATEGORY SELECTION
------------------------- */

function selectCategory(selectedCategory) {

    category = selectedCategory;

    let box = document.getElementById("subcategory-container");

    box.innerHTML = "";

    let subcategories = Object.keys(quizQuestions[category]);

    for (let i = 0; i < subcategories.length; i++) {

        let name = subcategories[i];

        let div = document.createElement("div");

        div.className = "subcategory-box";

        div.innerHTML =
            "<h3>" + name + "</h3>" +
            "<p>Test your " + name + " knowledge</p>";

        div.onclick = function() {
            selectSubcategory(name);
        };

        box.appendChild(div);
    }

    document.getElementById("category-section").style.display = "none";

    document.getElementById("subcategory-section").style.display = "block";
}


/* -------------------------
   SUBCATEGORY SELECTION
------------------------- */

function selectSubcategory(selectedSubcategory) {

    subcategory = selectedSubcategory;

    document.getElementById("subcategory-section").style.display = "none";

    document.getElementById("difficulty-section").style.display = "block";
}


/* -------------------------
   DIFFICULTY SELECTION
------------------------- */

function selectDifficulty(selectedDifficulty) {

    difficulty = selectedDifficulty;

    alert("You selected " + selectedDifficulty + " difficulty");
}


/* -------------------------
   START QUIZ
------------------------- */

function startQuiz() {

    if (difficulty == "") {
        alert("Please select a difficulty first");
        return;
    }

    /*
       We are using the same questions
       for all difficulty levels for now.
    */

    questions = quizQuestions[category][subcategory];

    questionNumber = 0;

    score = 0;

    document.getElementById("difficulty-section").style.display = "none";

    document.getElementById("quiz-section").style.display = "block";

    showQuestion();
}


/* -------------------------
   SHOW QUESTION
------------------------- */

function showQuestion() {

    let currentQuestion = questions[questionNumber];

    document.getElementById("question").innerText =
        currentQuestion.question;

    document.getElementById("question-number").innerText =
        "Question " +
        (questionNumber + 1) +
        " of " +
        questions.length;

    document.getElementById("score").innerText = score;


    let options = document.getElementsByClassName("option");

    for (let i = 0; i < options.length; i++) {

        options[i].innerText = currentQuestion.options[i];

        options[i].disabled = false;

        options[i].style.backgroundColor = "white";
    }
}


/* -------------------------
   CHECK ANSWER
------------------------- */

function checkAnswer(selectedOption) {

    let currentQuestion = questions[questionNumber];

    let options = document.getElementsByClassName("option");


    if (selectedOption == currentQuestion.answer) {

        score++;

        options[selectedOption].style.backgroundColor = "#b8f5c8";

    } else {

        options[selectedOption].style.backgroundColor = "#f5b8b8";

        options[currentQuestion.answer].style.backgroundColor = "#b8f5c8";
    }


    document.getElementById("score").innerText = score;


    // Disable all options after answering

    for (let i = 0; i < options.length; i++) {
        options[i].disabled = true;
    }
}


/* -------------------------
   NEXT QUESTION
------------------------- */

function nextQuestion() {

    questionNumber++;

    if (questionNumber < questions.length) {

        showQuestion();

    } else {

        showResult();
    }
}


/* -------------------------
   SHOW RESULT
------------------------- */

function showResult() {

    document.getElementById("quiz-section").style.display = "none";

    document.getElementById("result-section").style.display = "block";


    let total = questions.length;

    let wrong = total - score;


    document.getElementById("final-score").innerText =
        score + " / " + total;

    document.getElementById("correct-answers").innerText =
        score;

    document.getElementById("wrong-answers").innerText =
        wrong;
}

/*---------------------
Back to Category
---------------------*/

function goBackToCategory() {
    document.getElementById("category-section").style.display = "block";

    document.getElementById("subcategory-section").style.display = "none";

    document.getElementById("difficulty-section").style.display = "none";

    document.getElementById("quiz-section").style.display = "none";
}